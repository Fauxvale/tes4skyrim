# Well-known property names that are generated by the script converter for
# TES4-specific systems with no Skyrim equivalent. These records must be
# created in the output ESM so VMAD properties can reference them.
_WELL_KNOWN_PROPERTIES: dict[str, int] = {}   # populated by _create_tes4_special_records


def get_well_known_properties() -> dict:
    """Synthesized property name -> output FormID.

    Accessor rather than a direct import so object_scripts can bind these
    without a circular import. Built in the MAIN process (phase 0/0b) and read
    by the object-script plan, which is also main-process, so no worker ever
    sees an empty copy.
    """
    return _WELL_KNOWN_PROPERTIES


# Record types an MGEF Assoc. Item can name, plus LVLC for summon indirection.
_ASSOC_ITEM_SIGS = ('CREA', 'NPC_', 'WEAP', 'ARMO', 'CLOT', 'LIGH', 'LVLC')


def _mgef_records_with_masters(by_type: dict, ctx) -> list:
    """Every MGEF this plugin can reference: its own, plus its masters'.

    A dependent plugin normally defines no magic effects and points its items
    at the master's — so the effect index must include them, exactly as the
    outfit index includes the master's wardrobe.  The plugin's own records are
    appended LAST so an override of a master effect wins.
    """
    own = by_type.get('MGEF', [])
    if not ctx or not getattr(ctx, 'master_export', None):
        return own
    from_master = [rec for rec in ctx.master_export.values()
                   if rec.get('Signature') == 'MGEF']
    own_codes = {rec.get('EditorID') for rec in own}
    return [r for r in from_master
            if r.get('EditorID') not in own_codes] + own


def _build_assoc_item_index(by_type: dict, ctx=None) -> tuple:
    """(lvlc_first_entry, formid_signature) for MGEF Assoc. Item resolution.

    Skyrim's magic-effect archetypes are typed about what their Assoc. Item may
    be (`wbMGEFAssocItemDecider`): Summon Creature takes an NPC_, Bound Weapon
    a WEAP or ARMO.  Oblivion's MGEF just stores a FormID and says which KIND
    it is in its flags, so the converter has to look the target up to know
    whether it survives the type check.

    Two summon effects in Oblivion point at an LVLC (leveled creature list),
    which converts to an LVLN — a type Summon Creature does NOT accept.  Their
    first list entry stands in so the spell still summons something.

    The masters' records are indexed too: a dependent plugin's effects name
    the master's creatures, not its own.

    Returns ({lvlc out-FormID: first entry out-FormID}, {out-FormID: TES4 sig}).
    """
    sigs = {}
    lvlc_recs = []

    sources = []
    if ctx and getattr(ctx, 'master_export', None):
        sources.append(r for r in ctx.master_export.values()
                       if r.get('Signature') in _ASSOC_ITEM_SIGS)
    # The plugin's own records go LAST so an override wins the FormID.
    sources.append(r for sig in _ASSOC_ITEM_SIGS for r in by_type.get(sig, []))

    for source in sources:
        for rec in source:
            fid = get_formid(rec, 'FormID')
            if not fid:
                continue
            sig = rec.get('Signature')
            sigs[fid] = sig
            if sig == 'LVLC':
                lvlc_recs.append((fid, rec))

    lvlc_first = {}
    for fid, rec in lvlc_recs:
        # Lowest-level entry: the one an unleveled summon would produce first.
        best = None
        for i in range(get_int(rec, 'EntryCount')):
            entry = get_formid(rec, f'Entry[{i}].FormID')
            if not entry:
                continue
            level = get_int(rec, f'Entry[{i}].Level', 1)
            if best is None or level < best[0]:
                best = (level, entry)
        if best:
            lvlc_first[fid] = best[1]

    # A leveled list may nest another leveled list; follow the chain so the
    # answer is always a concrete creature, never an LVLN the archetype
    # rejects.  Bounded by the list count so a self-referential list (which
    # Oblivion permits and the CS never validated) cannot spin.
    for fid in list(lvlc_first):
        target = lvlc_first[fid]
        for _ in range(len(lvlc_first)):
            if sigs.get(target) != 'LVLC':
                break
            nxt = lvlc_first.get(target)
            if not nxt or nxt == target:
                break
            target = nxt
        lvlc_first[fid] = target if sigs.get(target) != 'LVLC' else 0

    return lvlc_first, sigs


def _create_tes4_special_records(writer: PluginWriter):
    """Create globals and factions needed by converted Papyrus scripts.

    TES4Fame / TES4Infamy: Replace Oblivion's GetPCFame/GetPCInfamy system.
    TES4CyrodiilCrimeFaction: Replace Oblivion's single crime faction system.

    FormIDs are stored in _WELL_KNOWN_PROPERTIES so VMAD builders can inject
    them as property values, eliminating the "fill in CK" step.
    """
    # TES4Fame — GlobalVariable (Float, initial 0.0)
    fame_fid = writer.alloc_formid()
    fame_subs = pack_string_subrecord('EDID', 'TES4Fame')
    fame_subs += pack_subrecord('FNAM', struct.pack('<B', ord('f')))
    fame_subs += pack_subrecord('FLTV', struct.pack('<f', 0.0))
    writer.add_record('GLOB', pack_record('GLOB', fame_fid, 0, fame_subs))
    _WELL_KNOWN_PROPERTIES['TES4Fame'] = fame_fid

    # TES4Infamy — GlobalVariable (Float, initial 0.0)
    infamy_fid = writer.alloc_formid()
    infamy_subs = pack_string_subrecord('EDID', 'TES4Infamy')
    infamy_subs += pack_subrecord('FNAM', struct.pack('<B', ord('f')))
    infamy_subs += pack_subrecord('FLTV', struct.pack('<f', 0.0))
    writer.add_record('GLOB', pack_record('GLOB', infamy_fid, 0, infamy_subs))
    _WELL_KNOWN_PROPERTIES['TES4Infamy'] = infamy_fid

    # TES4GoldFenced — GlobalVariable (Float, initial 0.0).
    # Oblivion's GetAmountSoldStolen/ModAmountSoldStolen track the GOLD VALUE of
    # stolen goods fenced (the Thieves Guild INFOs literally print
    # "Amount fenced: %.0f gold").  Skyrim keeps the counter only as a condition
    # function — there is no Papyrus native and no matching entry in the stat
    # table — so converted scripts back it with this global.  Reusing the
    # vanilla "Items Stolen" stat would be wrong twice over: it counts items
    # rather than gold, and the engine bumps it on every theft, so the TG rank
    # gates would trip without ever visiting a fence.
    fenced_fid = writer.alloc_formid()
    fenced_subs = pack_string_subrecord('EDID', 'TES4GoldFenced')
    fenced_subs += pack_subrecord('FNAM', struct.pack('<B', ord('f')))
    fenced_subs += pack_subrecord('FLTV', struct.pack('<f', 0.0))
    writer.add_record('GLOB', pack_record('GLOB', fenced_fid, 0, fenced_subs))
    _WELL_KNOWN_PROPERTIES['TES4GoldFenced'] = fenced_fid

    # TES4ControlsDisabled — GlobalVariable (Short, initial 0).
    # Oblivion's GetPlayerControlsDisabled has no Papyrus native (checked
    # vanilla Game.psc and SKSE — only the Disable/Enable writers exist), and
    # flattening the read to 0 is not neutral: it makes `== 1` permanently
    # false AND `== 0` permanently true, so a script that polls the state gets
    # both halves of its own sequencing wrong.  The converter owns both
    # writers, so the state is shadowed here: Game.DisablePlayerControls() and
    # Game.EnablePlayerControls() each also write this global, and the read
    # returns it.
    ctrl_fid = writer.alloc_formid()
    ctrl_subs = pack_string_subrecord('EDID', 'TES4ControlsDisabled')
    ctrl_subs += pack_subrecord('FNAM', struct.pack('<B', ord('s')))
    ctrl_subs += pack_subrecord('FLTV', struct.pack('<f', 0.0))
    writer.add_record('GLOB', pack_record('GLOB', ctrl_fid, 0, ctrl_subs))
    _WELL_KNOWN_PROPERTIES['TES4ControlsDisabled'] = ctrl_fid

    # TES4CyrodiilCrimeFaction — stands in for Oblivion's single global crime
    # faction, and is the receiver for most converted GetPCExpelled /
    # GotoJail / crime calls, so it has to be a REAL crime faction.
    #
    # It previously set CanBeOwner plus bits 7-11/13/16, which are Skyrim's
    # *Ignore* Crimes flags — the opposite of the intent (xEdit decodes the old
    # 0x0001AF80 as "IgnoreKills") — and never set Track Crime, without which
    # the engine accumulates no crime gold at all.  Its CRVA also used the wrong
    # struct layout and left every crime worth 0.  See convert_FACT in
    # record_types/actors.py for the layout and the vanilla-census amounts.
    crime_fid = writer.alloc_formid()
    crime_subs = pack_string_subrecord('EDID', 'TES4CyrodiilCrimeFaction')
    crime_subs += pack_string_subrecord('FULL', 'Cyrodiil Crime Faction')
    # DATA: Can Be Owner (bit 15) + Track Crime (bit 6)
    crime_subs += pack_subrecord('DATA', struct.pack('<I', 0x8000 | 0x0040))
    # CRVA — vanilla crime values (murder=1000, assault=40, trespass=5,
    # pickpocket=25, steal x1.0, escape=100), matching all 14 real Skyrim
    # crime factions.
    crime_subs += pack_subrecord(
        'CRVA', struct.pack('<BBHHHHHfHH', 1, 1, 1000, 40, 5, 25, 0, 1.0, 100, 0))
    writer.add_record('FACT', pack_record('FACT', crime_fid, 0, crime_subs))
    _WELL_KNOWN_PROPERTIES['TES4CyrodiilCrimeFaction'] = crime_fid

    print(f"  Created TES4 special records: "
          f"TES4Fame={fame_fid:08X}, TES4Infamy={infamy_fid:08X}, "
          f"TES4GoldFenced={fenced_fid:08X}, "
          f"TES4ControlsDisabled={ctrl_fid:08X}, "
          f"TES4CyrodiilCrimeFaction={crime_fid:08X}")


def _create_message_menu_records(writer: PluginWriter, plan: dict) -> dict:
    """One MESG per button-MessageBox call site (message_menus.py plan).

    Layout matches vanilla script-shown boxes (dunMiddenNamesMenuMSG): DESC =
    the message text, INAM = null (required leftover), DNAM bit 0 = Message
    Box (a modal with buttons, not a corner notification), one ITXT per
    button and no conditions — Show() returns the clicked ITXT's index, which
    is the same number the TES4 GetButtonPressed poll compared against.
    Returns {mesg_edid: formid} for _WELL_KNOWN_PROPERTIES.
    """
    name_to_fid = {}
    for edid_low in sorted(plan):
        for name, text, buttons in plan[edid_low]:
            fid = writer.alloc_formid()
            subs = pack_string_subrecord('EDID', name)
            subs += pack_string_subrecord('DESC', text)
            subs += pack_subrecord('INAM', struct.pack('<I', 0))
            subs += pack_subrecord('DNAM', struct.pack('<I', 1))
            for button in buttons:
                subs += pack_string_subrecord('ITXT', button)
            writer.add_record('MESG', pack_record('MESG', fid, 0, subs))
            name_to_fid[name] = fid
    return name_to_fid


def _create_ambient_gmst_overrides(writer: PluginWriter, by_type: dict):
    """Carry Oblivion's GLOBAL ambient-dialogue pacing across.

    Oblivion has no per-package chatter control — its package flags concern
    doors, speed, sneak, equipment and combat, nothing about dialogue (xEdit
    wbPackageFlags; UESP "Oblivion Mod:Mod File Format/PACK"). Pacing lives
    entirely in these game settings, and Skyrim's equivalents run far faster
    (greeting retry 5s vs Oblivion's 20s; idle chatter 10s vs Oblivion's
    authored 100s). Because 'GMST' is in SKIP_TYPES, none of that pacing was
    carried over and converted NPCs ran Skyrim's clock over Oblivion's much
    larger line pool — the constant-quipping defect.

    The TES4 export's own value wins when the record exists there (that is what
    Oblivion.esm actually shipped); otherwise the Oblivion.exe engine default
    recorded in AMBIENT_GMST_OVERRIDES is used.
    """
    authored = {}
    for rec in by_type.get('GMST', []):
        edid = get_str(rec, 'EditorID', '')
        if edid in AMBIENT_GMST_OVERRIDES:
            try:
                authored[edid] = float(get_str(rec, 'DATA.Value'))
            except (TypeError, ValueError):
                pass

    written = []
    for edid, (default, _is_float) in sorted(AMBIENT_GMST_OVERRIDES.items()):
        value = authored.get(edid, default)
        subs = pack_string_subrecord('EDID', edid)
        subs += pack_subrecord('DATA', struct.pack('<f', value))
        writer.add_record('GMST', pack_record(
            'GMST', writer.alloc_formid(), 0, subs))
        written.append(f"{edid}={value:g}"
                       + ('' if edid in authored else ' (exe default)'))
    print(f"  Ambient dialogue pacing (GMST): {', '.join(written)}")


def _create_vtyp_records(writer: PluginWriter):
    """Create custom VTYP records for all Oblivion races in the output plugin.

    All voice types are created from scratch — we never reference Skyrim.esm
    VTYPs.  Voice files go in Sound/Voice/<plugin>/<EditorID>/ and must match
    the EditorIDs created here (TES4Male*, TES4Female*).

    Updates VOICE_TYPE_MAP at runtime so NPC_ converters pick the right FormID.

    DNAM flags: bit 0 = AllowDefaultDialogue, bit 1 = Female
      Male   voices: DNAM = 1
      Female voices: DNAM = 3
    """
    for vtyp_edid, (race_edid, gender) in CUSTOM_VTYP_EDIDS.items():
        fid = writer.alloc_formid()
        dnam = 3 if gender == 'Female' else 1
        subs = pack_string_subrecord('EDID', vtyp_edid)
        subs += pack_subrecord('DNAM', struct.pack('<B', dnam))
        writer.add_record('VTYP', pack_record('VTYP', fid, 0, subs))
        set_voice_type(race_edid, gender, fid)


def _read_tes4_masters(export_dir: str) -> list:
    """The plugin's TES4 master NAMES, from the export's _HEADER.txt.

    The export header is the authority, not the source binary: the binary lives
    in the configured Oblivion data folder and may simply not be there (a Nehrim
    plugin against a Steam Oblivion install), in which case the caller's
    binary-derived master list comes back EMPTY while the export still says the
    plugin has masters. Trusting the count from one source and the names from
    the other made `masters[len(masters) - count:]` slice off the tail of
    ['Skyrim.esm'] and demand a converted `output/Skyrim.esm/Skyrim.esm` —
    Translation.esp aborted with "convert the master first: Skyrim.esm".
    """
    path = os.path.join(export_dir, '_HEADER.txt')
    if not os.path.isfile(path):
        return []
    names = []
    with open(path, 'r', encoding='utf-8') as f:
        for line in f:
            if line.startswith('Master['):
                _, _, val = line.partition('=')
                if val.strip():
                    names.append(val.strip())
    return names


def import_plugin(export_dir: str, output_path: str, masters: list = None,
                  is_esm: bool = True, skip_types: set = None,
                  output_root: str = None):
    """
    Main import entry point. Reads exports and writes a TES5 plugin.

    Args:
        export_dir: Directory containing per-type .txt export files
        output_path: Path for the output .esm/.esp file
        masters: List of master file names (e.g., ['Skyrim.esm'])
        is_esm: Whether to create an ESM (True) or ESP (False)
        skip_types: Additional types to skip
        output_root: Root output dir holding the converted masters at
                     <root>/<Master>/<Master>. Required when the plugin has
                     TES4 masters — its overrides are merged against them.
                     Defaults to the parent of this plugin's output folder.
    """
    if masters is None:
        masters = ['Skyrim.esm']
    if skip_types is None:
        skip_types = set()
    all_skip = SKIP_TYPES | skip_types

    # Per-plugin output dirs are named after the plugin (output/Oblivion.esm/ is
    # a FOLDER); given the folder, write <folder>/<folder-name> inside it rather
    # than failing to overwrite a directory with a file at the end of the run.
    # convert.py always creates that folder up front and passes the inner path,
    # so this only fires for a direct CLI run against an existing plugin dir.
    if os.path.isdir(output_path):
        output_path = os.path.join(
            output_path, os.path.basename(os.path.normpath(output_path)))
    plugin_out_dir = os.path.dirname(output_path)

    # Per-phase wall-clock reporting so slow phases are visible in the log.
    _phase_t = time.time()

    def _phase_done(label: str):
        nonlocal _phase_t
        now = time.time()
        print(f"  [phase] {label}: {now - _phase_t:.1f}s")
        _phase_t = now

    # Finer-grained timer for the phase-0 pre-scans (prints only slow steps).
    _step_t = time.time()

    def _step_done(label: str):
        nonlocal _step_t
        now = time.time()
        if now - _step_t >= 1.0:
            print(f"    [phase0] {label}: {now - _step_t:.1f}s")
        _step_t = now

    # How many masters the file had in TES4. Everything at a load-order index
    # below this is an override of one of those masters; the plugin's own
    # records sit at exactly this index.
    tes4_master_names = _read_tes4_masters(export_dir)
    num_tes4_masters = len(tes4_master_names)
    # Reconcile the caller's master list with the export header. The caller
    # derives its list from the SOURCE BINARY, which may be missing from the
    # configured data folder; the header always ships with the export. Whenever
    # they disagree, the header's TES4 masters are appended so the trailing
    # `num_tes4_masters` entries really are those masters.
    if num_tes4_masters:
        tail = masters[len(masters) - num_tes4_masters:]
        if [n.lower() for n in tail] != [n.lower() for n in tes4_master_names]:
            new_masters = [m for m in masters
                           if m.lower() not in
                           {n.lower() for n in tes4_master_names}]
            masters = new_masters + tes4_master_names
            print(f"  Masters (from export header): {', '.join(masters)}")
    ctx = None
    if num_tes4_masters:
        print(f"  TES4 masters: {num_tes4_masters} "
              f"(records below index {num_tes4_masters:02X} are overrides)")
        # An override is emitted as the MASTER's converted record with only the
        # author's changes applied, so we need three things from the master:
        # its converted bytes, the companion pairings its run recorded, and its
        # raw export (to tell what the author actually changed). OverrideContext
        # bundles all three (see tes5_import/overrides.py).
        if output_root is None:
            output_root = os.path.dirname(plugin_out_dir) or '.'
        _t = time.time()
        ctx = OverrideContext(export_dir, masters, num_tes4_masters,
                              output_root)
        print(f"  Master: {len(ctx.master_index)} converted records, "
              f"{len(ctx.master_manifest)} manifest entries, "
              f"{len(ctx)} exported records ({time.time() - _t:.1f}s)")
        if not len(ctx):
            # No master export to diff against: every record would be treated
            # as new, silently duplicating the master. The warning has already
            # printed; run without an override context.
            ctx = None

    print(f"Reading exports from: {export_dir}")
    t0 = time.time()

    # Parse all records
    all_records = parse_export_directory(export_dir)
    # A record the author DELETED and that is this plugin's OWN (not an
    # override of a master's) is pure bloat: there is nothing to remove, so
    # converting it would emit a live record the author had thrown away. The
    # export carries it as an empty stub, so it would also convert to a
    # contentless REFR with no NAME. Overrides are NOT filtered here — a
    # deleted override is meaningful and OverrideContext.build turns it into a
    # proper deletion stub (see overrides.make_deleted_record).
    if all_records:
        keep = []
        dropped_deleted = 0
        for rec in all_records:
            if (int(rec.get('RecordFlags') or 0) & OVERRIDE_DELETED_FLAG
                    and (ctx is None or ctx.master_record(rec) is None)):
                dropped_deleted += 1
                continue
            keep.append(rec)
        if dropped_deleted:
            print(f"  Dropped {dropped_deleted} record(s) the author deleted "
                  f"and that this plugin itself defines")
            all_records = keep
    by_type = group_records_by_type(all_records)

    t1 = time.time()
    print(f"  Parsed {len(all_records)} records in {len(by_type)} types ({t1-t0:.2f}s)")
    _phase_done('parse export text')

    for sig in sorted(by_type.keys()):
        special_types = {'LTEX', 'SOUN', 'CELL', 'WRLD', 'REFR', 'ACHR', 'ACRE', 'LAND', 'DIAL', 'INFO'}
        status = "SKIP" if sig in all_skip else ("CONVERT" if sig in IMPORT_DISPATCH or sig in special_types else "UNKNOWN")
        print(f"  {sig}: {len(by_type[sig])} records [{status}]")

    # Create writer
    writer = PluginWriter(masters=masters, is_esm=is_esm,
                          description="Converted from TES4 by tes4_export")

    # Every distinct BOOK model in the plugin, so convert_BOOK can resolve
    # inventory-art basenames through the same collision-aware map the asset
    # side uses (asset_convert/book_inam.py).  Two BOOK models can share a
    # leaf filename across directories; only the whole-plugin view can tell
    # which one keeps the bare name, and the STAT must agree with the mesh.
    writer.export_dir = export_dir
    try:
        from asset_convert.book_inam import distinct_book_models
        writer.book_models = distinct_book_models(export_dir)
    except Exception as exc:
        print(f"  [book INAM] model list unavailable ({exc}); using leaf names")
        writer.book_models = []

    # Set FormID remapping. The TES5 master list is the TES4 one with N new
    # masters (Skyrim.esm) PREPENDED, so every TES4 load-order index — the
    # plugin's own and its masters' alike — shifts up by exactly N.
    #   Oblivion.esm, masters=['Skyrim.esm'], tes4 masters=0 → offset 1:
    #     own 0x00XXXXXX → 0x01XXXXXX
    #   Translation.esp, masters=['Skyrim.esm','Nehrim.esm'],
    #   tes4 masters=['Nehrim.esm'] → offset 1:
    #     Nehrim override 0x00XXXXXX → 0x01XXXXXX  (overrides Nehrim.esm)
    #     own new record  0x01XXXXXX → 0x02XXXXXX
    # Using len(masters) here instead would shift overrides to the plugin's own
    # index, turning every override into a duplicate new record.
    num_new_masters = len(masters) - num_tes4_masters
    set_formid_index_offset(num_new_masters)

    # Determine next FormID from the maximum in the export (before remapping applies)
    # Must scan ALL FormIDs including those in cross-references to avoid collisions
    # Only the plugin's OWN records can constrain its next object id — an
    # override's low bytes belong to the master's id space, not ours.
    max_formid = 0
    for rec in all_records:
        fid_raw = int(rec.get('FormID', '0'), 16)
        if (fid_raw >> 24) & 0xFF != num_tes4_masters:
            continue
